"""
This function summarise the input and the output data by providing statistical information for each of the input features
as well as for each output channel.
Inputs:     1) X:       input feature vector (based on aggregated consumption)
            2) y:       output vector (electrical appliance consumption)
            3) setup:   includes all simulation variables
Outputs:    None
"""

#######################################################################################################################
# Import libs
#######################################################################################################################
# ==============================================================================
# Internal
# ==============================================================================

# ==============================================================================
# External
# ==============================================================================
import numpy as np
import copy
from texttable import Texttable


#######################################################################################################################
# Additional Functions
#######################################################################################################################
def rms(x):
    return np.sqrt(x.dot(x)/x.size)


#######################################################################################################################
# Function
#######################################################################################################################
def summaryData(X, y, setupDat):
    ###################################################################################################################
    # MSG IN
    ###################################################################################################################
    print("INFO: Summary of the data")

    ###################################################################################################################
    # Init
    ###################################################################################################################
    X = X.drop(['time', 'id'], axis=1)
    y = y.drop(['time', 'id'], axis=1)
    F = len(X.columns)
    M = len(y.columns)
    namesF = X.columns
    unitsF = setupDat['inpUnits']
    namesM = y.columns
    unitsM = setupDat['outUnits']

    ###################################################################################################################
    # Calculation
    ###################################################################################################################
    # ==============================================================================
    # Aggregated Data
    # ==============================================================================
    # ------------------------------------------
    # Init
    # ------------------------------------------
    table = Texttable()
    table.set_deco(Texttable.HEADER)
    table.set_cols_dtype(['i', 't', 't', 't', 't', 't', 't', 't', 't', 't'])
    table.set_cols_align(["l", "l", "l", "r", "r", "r", "r", "r", "r", "r"])
    table.set_cols_width([4, 15, 8, 9, 9, 9, 9, 9, 9, 9])
    table.header(['ID', 'Feature', 'Unit', 'MIN', 'MAX', 'AVG', 'RMS', 'SUM', 'STD', 'Noise'])

    # ------------------------------------------
    # Msg In
    # ------------------------------------------
    print("INFO: Aggregated data")
    print('-' * 115)
    print('-' * 115)

    # ------------------------------------------
    # Iterate
    # ------------------------------------------
    for i in range(0, F):
        col = X.iloc[:, i]

        v_min = np.min(col)
        v_max = np.max(col)
        v_avg = np.mean(col)
        v_rms = rms(col)
        v_sum = np.sum(col) / 3.6e6
        v_std = np.std(col)
        v_noise = (1 - np.sum(np.sum(y.iloc[:, :])) / np.sum(col)) * 100

        table.add_row([
            i,
            namesF[i],
            unitsF[namesF[i]][0],
            f"{v_min:.2f}",
            f"{v_max:.2f}",
            f"{v_avg:.2f}",
            f"{v_rms:.2f}",
            f"{v_sum:.2f}",
            f"{v_std:.2f}",
            f"{v_noise:.2f}",
        ])

    print(table.draw())
    print("\n")

    # ==============================================================================
    # Appliance Data
    # ==============================================================================
    # ------------------------------------------
    # Init
    # ------------------------------------------
    table = Texttable()
    table.set_deco(Texttable.HEADER)
    table.set_cols_dtype(['i', 't', 't', 't', 't', 't', 't', 't', 't', 't'])
    table.set_cols_align(["l", "l", "l", "r", "r", "r", "r", "r", "r", "r"])
    table.set_cols_width([4, 15, 8, 9, 9, 9, 9, 9, 9, 9])
    table.header(['ID', 'Device', 'Unit', 'MIN', 'MAX', 'AVG', 'RMS', 'SUM', 'STD', 'ON'])

    # ------------------------------------------
    # Msg In
    # ------------------------------------------
    print("INFO: Appliance data")
    print('-' * 115)
    print('-' * 115)

    # ------------------------------------------
    # Iterate
    # ------------------------------------------
    for i in range(0, M):
        col = y.iloc[:, i]

        activity = copy.deepcopy(col)
        activity[activity < setupDat['threshold']] = 0
        activity[activity >= setupDat['threshold']] = 1

        v_min = np.min(col)
        v_max = np.max(col)
        v_avg = np.mean(col)
        v_rms = rms(col)
        v_sum = np.sum(col) / 3.6e6
        v_std = np.std(col)
        v_on = np.sum(activity) / len(activity) * 100

        table.add_row([
            i,
            namesM[i],
            unitsM[namesM[i]][0],
            f"{v_min:.2f}",
            f"{v_max:.2f}",
            f"{v_avg:.2f}",
            f"{v_rms:.2f}",
            f"{v_sum:.2f}",
            f"{v_std:.2f}",
            f"{v_on:.2f}",
        ])

    print(table.draw())
    print("\n")

    ###################################################################################################################
    # Return
    ###################################################################################################################
    return []
